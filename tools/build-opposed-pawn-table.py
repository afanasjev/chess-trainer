"""Export exact offline KPKP/promotion tables using Fathom and local Syzygy files.
Usage: python3 tools/build-opposed-pawn-table.py --tables /path/to/syzygy
No downloads are performed. See tools/ENDGAME_TABLES.md for required files.
"""
import argparse,base64,os,subprocess,tempfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def pack(b):
 o=bytearray();seen={};i=0;anchor=0
 def ext(n):
  while n>=255:o.append(255);n-=255
  o.append(n)
 while i+4<=len(b):
  key=b[i:i+4];prev=seen.get(key,-100000);seen[key]=i
  if i-prev>65535 or b[prev:prev+4]!=key:i+=1;continue
  length=4
  while i+length<len(b) and b[prev+length]==b[i+length]:length+=1
  lit=i-anchor;o.append((min(lit,15)<<4)|min(length-4,15))
  if lit>=15:ext(lit-15)
  o.extend(b[anchor:i]);offset=i-prev;o.extend((offset&255,offset>>8))
  if length>=19:ext(length-19)
  end=i+length
  for j in range(i+1,end):
   if j+4<=len(b):seen[b[j:j+4]]=j
  i=end;anchor=i
 lit=len(b)-anchor;o.append(min(lit,15)<<4)
 if lit>=15:ext(lit-15)
 o.extend(b[anchor:]);return o

def export_files(main,promotion):
 source='// Exact Syzygy KPKP WDL/DTZ and Q/R/B/N promotion boundaries.\n// Generated by tools/build-opposed-pawn-table.py; LZ4 blocks.\n(()=>{const decode=(chunks,size)=>{const b=Uint8Array.from(atob(chunks.join("")),c=>c.charCodeAt(0)),out=new Uint8Array(size);let i=0,j=0;const length=n=>{if(n===15){let x;do{x=b[i++];n+=x}while(x===255)}return n};while(i<b.length){const tag=b[i++],lit=length(tag>>4);out.set(b.subarray(i,i+lit),j);i+=lit;j+=lit;if(i===b.length)break;const offset=b[i++]|(b[i++]<<8),n=length(tag&15)+4;for(let k=0;k<n;k++){out[j]=out[j-offset];j++}}if(j!==size)throw Error("Invalid opposed-pawn table");return out};\n'
 for name,data,size in [('OPPOSED_PAWN_TABLE',main,9437184),('PAWN_PROMOTION_TABLE',promotion,3145728)]:
  assert len(data)==size
  compressed=pack(data);s=base64.b64encode(compressed).decode();chunks=[s[i:i+120] for i in range(0,len(s),120)]
  source+='window.'+name+'=decode([\n'+',\n'.join('"'+c+'"' for c in chunks)+f'\n],{size});\n'
  print(name,'raw',len(data),'compressed',len(compressed))
 source+='})();\n';(root/'dist/opposed-pawn-table.js').write_text(source)
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--tables',type=Path,required=True);args=ap.parse_args()
 for name in ['KPvKP','KQvKP','KRvKP','KBvKP','KNvKP','KPvK','KQvK','KRvK','KBvK','KNvK']:
  if not (args.tables/(name+'.rtbw')).exists():raise SystemExit('Missing '+name+'.rtbw')
 for name in ['KPvKP','KPvK']:
  if not (args.tables/(name+'.rtbz')).exists():raise SystemExit('Missing '+name+'.rtbz')
 with tempfile.TemporaryDirectory() as temp:
  temp=Path(temp)
  subprocess.run([os.environ.get('CC','cc'),'-O3','-std=c11','-I'+str(root/'tools/vendor/fathom'),str(root/'tools/build-opposed-pawn-table.c'),'-o',str(temp/'build')],check=True)
  subprocess.run([str(temp/'build'),str(args.tables.resolve()),str(temp/'main.bin'),str(temp/'promotion.bin')],check=True)
  export_files((temp/'main.bin').read_bytes(),(temp/'promotion.bin').read_bytes())
